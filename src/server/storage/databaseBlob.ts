// =============================================================================
// Database-backed blob store (ATTACHMENT_STORAGE=database).
//
// Bytes live in the AttachmentBlob table, so no object storage account is
// needed. Vercel request bodies are about 4.5 MB, which caps each file at 4 MB
// (see DATABASE_ATTACHMENT_MAX_BYTES). Watch the Neon storage quota.
// =============================================================================

import { prismaClient } from "../data/prismaStore";
import { validateBlobKey, type BlobPutOptions, type BlobStore } from "./blobPort";

/** The subset of the Prisma AttachmentBlob delegate this store uses. */
export interface AttachmentBlobTable {
  upsert(args: { where: { id: string }; create: { id: string; data: Buffer }; update: { data: Buffer } }): Promise<unknown>;
  findUnique(args: { where: { id: string } }): Promise<{ data: Uint8Array } | null>;
  deleteMany(args: { where: { id: string } }): Promise<{ count: number }>;
}

export class DatabaseBlobStore implements BlobStore {
  // The cast bridges Prisma's generated Bytes typing (Buffer<ArrayBuffer>) to the narrower port.
  constructor(private readonly table: () => AttachmentBlobTable = () => prismaClient().attachmentBlob as unknown as AttachmentBlobTable) {}

  async put(key: string, bytes: Buffer, options?: BlobPutOptions): Promise<string> {
    void options;
    validateBlobKey(key);
    await this.table().upsert({ where: { id: key }, create: { id: key, data: bytes }, update: { data: bytes } });
    return `db://${key}`;
  }

  async get(key: string): Promise<Buffer | null> {
    const row = await this.table().findUnique({ where: { id: validateBlobKey(key) } });
    return row ? Buffer.from(row.data) : null;
  }

  async delete(key: string): Promise<boolean> {
    const result = await this.table().deleteMany({ where: { id: validateBlobKey(key) } });
    return result.count > 0;
  }
}
